def build_key(df) -> "object":
    """복합키 Series 를 만든다. 구분자는 데이터에 나타나지 않는 문자를 쓴다."""
    return df[KEY_COLUMNS].astype(str).agg("\x1f".join, axis=1)


def validate_headers(header_by_letter: dict[str, object]) -> list[str]:
    """실제 헤더 텍스트를 기대값과 대조해 경고 목록을 만든다."""
    warnings: list[str] = []
    for letter, expected in EXPECTED_HEADERS.items():
        actual = header_by_letter.get(letter)
        actual_text = "" if actual is None else str(actual).strip()
        if actual_text != expected:
            warnings.append(
                f"{letter}열 헤더가 다릅니다: 기대 '{expected}' / 실제 '{actual_text}'"
            )
    return warnings
